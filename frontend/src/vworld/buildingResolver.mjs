export function resolveVWorldBuilding(modelName) {
  const building = VWORLD_BUILDINGS.get(modelName);
  if (!building) return null;

  const [shortId, displayName] = building;
  return {
    MODEL_NAME: modelName,
    elementId: `${ELEMENT_ID_PREFIX}${shortId}`,
    displayName,
  };
}
